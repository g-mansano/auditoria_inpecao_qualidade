-- Schema completo. SQL portável entre PostgreSQL e H2 em modo PostgreSQL.

-- ---------------------------------------------------------------- usuários e sessões
CREATE TABLE usuario (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(60)  NOT NULL UNIQUE,
    nome         VARCHAR(150) NOT NULL,
    senha_hash   VARCHAR(200) NOT NULL,
    papel        VARCHAR(20)  NOT NULL,
    ativo        BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Revisar formulários (ADMIN sempre pode).
    pode_revisar BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Guarda apenas o SHA-256 do token; o token em si só existe no aparelho do usuário.
CREATE TABLE token_acesso (
    token_hash  VARCHAR(64) PRIMARY KEY,
    usuario_id  BIGINT NOT NULL REFERENCES usuario (id),
    criado_em   TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_em   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------- formulários
-- Uma linha por formulário, editada no lugar a cada revisão (o id não muda).
CREATE TABLE template_checklist (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(60)  NOT NULL,
    revisao             VARCHAR(10)  NOT NULL,
    titulo              VARCHAR(200) NOT NULL,
    -- AUDITORIA (checklist) ou INSPECAO_OP (inspeção diária de ordens de produção).
    tipo                VARCHAR(20)  NOT NULL DEFAULT 'AUDITORIA',
    -- Nome curto do cartão na tela inicial e a ordem dos cartões.
    nome                VARCHAR(60),
    ordem               INT NOT NULL DEFAULT 0,
    -- "Auditoria Interna", "Auditoria Housekeeping"... (cabeçalho "... Nº").
    rotulo_auditoria    VARCHAR(60)  NOT NULL DEFAULT 'Auditoria Interna',
    -- Rótulo da coluna de referência normativa; nulo = formulário sem essa coluna.
    rotulo_referencia   VARCHAR(40),
    usa_processo        BOOLEAN NOT NULL DEFAULT FALSE,
    usa_documentos      BOOLEAN NOT NULL DEFAULT TRUE,
    -- Campo "Local / área" por item.
    usa_local           BOOLEAN NOT NULL DEFAULT FALSE,
    -- Escala de resposta: "valor:sigla:rótulo" separados por "|". O valor é sempre C, NC, OM ou NA
    -- (guardado no banco); a sigla e o rótulo são o que aparece na tela e na impressão.
    opcoes_conformidade VARCHAR(300) NOT NULL
        DEFAULT 'C:C:Conforme|NC:NC:Não Conforme|OM:OM:Oportunidade de Melhoria|NA:NA:Não Aplicável',
    -- Conclusão exige nº de registro (RNC/NC/FI) em toda resposta NC.
    exige_registro_nc   BOOLEAN NOT NULL DEFAULT TRUE,
    escopo_padrao       VARCHAR(4000),
    -- Textos rápidos para o campo de orientação, separados por "|".
    sugestoes_evidencia VARCHAR(500),
    -- Rodapé de cada folha impressa; a revisão troca o número e a data.
    rodape              VARCHAR(200),
    ativo               BOOLEAN NOT NULL DEFAULT TRUE,
    -- Controle de concorrência entre revisores (sobe a cada salvamento).
    versao              BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_template_codigo_revisao UNIQUE (codigo, revisao)
);

-- Sem UNIQUE em (template_id, numero): a revisão renumera no lugar.
CREATE TABLE pergunta (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id        BIGINT NOT NULL REFERENCES template_checklist (id),
    numero             INT NOT NULL,
    -- CHECKLIST (lista principal) ou CAMPO (roteiro de inspeção por setor).
    secao              VARCHAR(20) NOT NULL DEFAULT 'CHECKLIST',
    -- Capítulo, etapa ou setor.
    grupo              VARCHAR(200),
    clausula           VARCHAR(60),
    texto              VARCHAR(2000) NOT NULL,
    processo_padrao    VARCHAR(500),
    documentos_padrao  VARCHAR(2000),
    orientacao_padrao  VARCHAR(2000),
    responsavel_padrao VARCHAR(150),
    -- Escala própria da pergunta (ex.: EPI = S/N/P). Nulo = escala do formulário.
    escala             VARCHAR(10)
);

-- Registro de cada salvamento de revisão.
CREATE TABLE revisao_formulario (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL REFERENCES template_checklist (id),
    revisao     VARCHAR(10) NOT NULL,
    nova        BOOLEAN NOT NULL,
    alteradas   INT NOT NULL,
    novas       INT NOT NULL,
    removidas   INT NOT NULL,
    auditorias  INT NOT NULL,
    salvo_por   VARCHAR(150) NOT NULL,
    salvo_em    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Histórico das revisões: pergunta antes -> depois.
CREATE TABLE revisao_formulario_detalhe (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revisao_id BIGINT NOT NULL REFERENCES revisao_formulario (id),
    numero     INT,
    tipo       VARCHAR(12) NOT NULL,
    antes      VARCHAR(2100),
    depois     VARCHAR(2100)
);

-- ---------------------------------------------------------------- permissões por formulário
-- Sem linha = sem acesso. ADMIN acessa tudo.
CREATE TABLE permissao_formulario (
    usuario_id  BIGINT NOT NULL REFERENCES usuario (id),
    template_id BIGINT NOT NULL REFERENCES template_checklist (id),
    nivel       VARCHAR(10) NOT NULL,
    PRIMARY KEY (usuario_id, template_id)
);

CREATE TABLE registro_permissao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT NOT NULL REFERENCES usuario (id),
    template_id    BIGINT NOT NULL REFERENCES template_checklist (id),
    nivel_anterior VARCHAR(10),
    nivel_novo     VARCHAR(10),
    alterado_por   VARCHAR(150) NOT NULL,
    alterado_em    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------- auditorias
CREATE TABLE auditoria (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero              VARCHAR(30) NOT NULL,
    data_inicio         DATE NOT NULL,
    data_fim            DATE,
    auditores           VARCHAR(1000) NOT NULL,
    escopo              VARCHAR(4000),
    status              VARCHAR(20) NOT NULL,
    template_id         BIGINT NOT NULL REFERENCES template_checklist (id),
    -- Check-out: só este usuário, neste aparelho, edita.
    editor_id           BIGINT REFERENCES usuario (id),
    editor_dispositivo  VARCHAR(64),
    checkout_em         TIMESTAMP WITH TIME ZONE,
    criado_por          VARCHAR(60) NOT NULL,
    criado_em           TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em       TIMESTAMP WITH TIME ZONE NOT NULL,
    concluido_em        TIMESTAMP WITH TIME ZONE,
    -- Exclusão lógica: some das listas, mas o registro e a trilha permanecem.
    excluida            BOOLEAN NOT NULL DEFAULT FALSE,
    excluida_por        VARCHAR(60),
    excluida_em         TIMESTAMP WITH TIME ZONE,
    -- Concluída uma vez, fica na revisão em que foi feita: guarda uma cópia do que imprime.
    revisao_congelada   BOOLEAN NOT NULL DEFAULT FALSE,
    snap_identificacao  VARCHAR(200),
    snap_titulo         VARCHAR(200),
    snap_rodape         VARCHAR(200),
    versao              BIGINT NOT NULL DEFAULT 0
);

-- Texto da pergunta copiado do formulário na criação: uma revisão só chega às auditorias
-- em andamento que nunca foram concluídas.
CREATE TABLE item_auditoria (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditoria_id        BIGINT NOT NULL REFERENCES auditoria (id),
    pergunta_id         BIGINT,
    numero              INT NOT NULL,
    secao               VARCHAR(20) NOT NULL DEFAULT 'CHECKLIST',
    grupo               VARCHAR(200),
    clausula            VARCHAR(60),
    pergunta            VARCHAR(2000) NOT NULL,
    processo            VARCHAR(500),
    documentos          VARCHAR(2000),
    orientacao          VARCHAR(2000),
    responsavel         VARCHAR(150),
    local               VARCHAR(200),
    evidencias          VARCHAR(20000),
    conformidade        VARCHAR(2),
    rnc                 VARCHAR(60),
    atualizado_em       TIMESTAMP WITH TIME ZONE,
    atualizado_por      VARCHAR(60),
    alterado_em_cliente TIMESTAMP WITH TIME ZONE,
    -- Pergunta alterada por uma revisão: precisa de nova resposta.
    alterada_na_revisao VARCHAR(10),
    alterada_em         TIMESTAMP WITH TIME ZONE,
    -- Pergunta removida por uma revisão (exclusão lógica).
    removido            BOOLEAN NOT NULL DEFAULT FALSE,
    removido_na_revisao VARCHAR(10),
    removido_visto      BOOLEAN NOT NULL DEFAULT FALSE
);

-- Anexos nunca são apagados fisicamente (controle de registros).
CREATE TABLE anexo (
    id            UUID PRIMARY KEY,
    item_id       BIGINT NOT NULL REFERENCES item_auditoria (id),
    nome_original VARCHAR(255) NOT NULL,
    content_type  VARCHAR(120) NOT NULL,
    tamanho       BIGINT NOT NULL,
    sha256        VARCHAR(64) NOT NULL,
    caminho       VARCHAR(500) NOT NULL,
    enviado_por   VARCHAR(60) NOT NULL,
    enviado_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    excluido      BOOLEAN NOT NULL DEFAULT FALSE,
    excluido_por  VARCHAR(60),
    excluido_em   TIMESTAMP WITH TIME ZONE
);

-- Trilha de auditoria: uma linha por campo alterado ou evento (só INSERT).
CREATE TABLE registro_alteracao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auditoria_id   BIGINT NOT NULL REFERENCES auditoria (id),
    item_numero    INT,
    evento         VARCHAR(40) NOT NULL,
    campo          VARCHAR(40),
    valor_anterior VARCHAR(20000),
    valor_novo     VARCHAR(20000),
    usuario        VARCHAR(60) NOT NULL,
    dispositivo    VARCHAR(64),
    registrado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------- inspeção de OPs (ids gerados no aparelho)
-- "Uma por inspetor por dia" vale só entre as não excluídas: a regra fica no serviço.
CREATE TABLE inspecao_dia (
    id             VARCHAR(36) PRIMARY KEY,
    template_id    BIGINT NOT NULL REFERENCES template_checklist (id),
    data           DATE NOT NULL,
    inspetor_id    BIGINT NOT NULL REFERENCES usuario (id),
    status         VARCHAR(20) NOT NULL,
    finalizada_em  TIMESTAMP WITH TIME ZONE,
    criado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    excluida       BOOLEAN NOT NULL DEFAULT FALSE,
    excluida_por   VARCHAR(60),
    excluida_em    TIMESTAMP WITH TIME ZONE
);

CREATE TABLE inspecao_op (
    id                  VARCHAR(36) PRIMARY KEY,
    dia_id              VARCHAR(36) NOT NULL REFERENCES inspecao_dia (id),
    ordem               INT NOT NULL,
    numero_op           VARCHAR(60),
    codigo_produto      VARCHAR(120),
    excluida            BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em           TIMESTAMP WITH TIME ZONE NOT NULL,
    alterado_em_cliente TIMESTAMP WITH TIME ZONE
);

-- Tópico da OP: cópia da pergunta no momento em que a OP foi criada.
CREATE TABLE inspecao_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op_id      VARCHAR(36) NOT NULL REFERENCES inspecao_op (id),
    numero     INT NOT NULL,
    topico     VARCHAR(2000) NOT NULL,
    escala     VARCHAR(10),
    valor      VARCHAR(4),
    observacao VARCHAR(4000),
    CONSTRAINT uk_inspecao_item UNIQUE (op_id, numero)
);

CREATE TABLE inspecao_lote (
    id              VARCHAR(36) PRIMARY KEY,
    op_id           VARCHAR(36) NOT NULL REFERENCES inspecao_op (id),
    lote            VARCHAR(120),
    data_fabricacao VARCHAR(40),
    excluido        BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE anexo_inspecao (
    id            VARCHAR(36) PRIMARY KEY,
    item_id       BIGINT NOT NULL REFERENCES inspecao_item (id),
    nome_original VARCHAR(255) NOT NULL,
    content_type  VARCHAR(120) NOT NULL,
    tamanho       BIGINT NOT NULL,
    sha256        VARCHAR(64) NOT NULL,
    caminho       VARCHAR(500) NOT NULL,
    enviado_por   VARCHAR(60) NOT NULL,
    enviado_em    TIMESTAMP WITH TIME ZONE NOT NULL,
    excluido      BOOLEAN NOT NULL DEFAULT FALSE,
    excluido_por  VARCHAR(60),
    excluido_em   TIMESTAMP WITH TIME ZONE
);

-- Trilha da inspeção (só INSERT).
CREATE TABLE registro_inspecao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_id         VARCHAR(36) NOT NULL REFERENCES inspecao_dia (id),
    op_id          VARCHAR(36),
    numero_op      VARCHAR(60),
    evento         VARCHAR(40) NOT NULL,
    campo          VARCHAR(2100),
    valor_anterior VARCHAR(4000),
    valor_novo     VARCHAR(4000),
    usuario        VARCHAR(60) NOT NULL,
    dispositivo    VARCHAR(64),
    registrado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_item_auditoria ON item_auditoria (auditoria_id);
CREATE INDEX ix_anexo_item ON anexo (item_id);
CREATE INDEX ix_registro_auditoria ON registro_alteracao (auditoria_id, registrado_em);
CREATE INDEX ix_token_usuario ON token_acesso (usuario_id);
CREATE INDEX ix_pergunta_template ON pergunta (template_id);
CREATE INDEX ix_inspecao_op_dia ON inspecao_op (dia_id);
CREATE INDEX ix_registro_inspecao_dia ON registro_inspecao (dia_id);
